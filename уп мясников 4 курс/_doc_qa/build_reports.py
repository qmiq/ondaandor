def is_red(paragraph) -> bool:
    """Определяет, содержит ли абзац исходный красный текст шаблона."""
    return any(
        run.font.color is not None and run.font.color.rgb is not None
        and str(run.font.color.rgb).upper() in RED
        for run in paragraph.runs
    )


def nearest_heading(paragraphs, position: int) -> str:
    """Ищет ближайший непустой чёрный абзац, задающий заголовок шага."""
    for prior in reversed(paragraphs[:position]):
        if prior.text.strip() and not is_red(prior):
            return prior.text.strip()
    return ""


