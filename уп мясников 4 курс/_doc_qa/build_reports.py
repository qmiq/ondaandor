def set_text(paragraph, value: str, *, align=None, first_indent=True):
    """Заменяет содержимое абзаца, сохраняя стиль шаблона и задавая ГОСТ-шрифт."""
    paragraph.clear()
    run = paragraph.add_run(value)
    run.font.name = FONT
    run.font.size = Pt(14)
    run.font.color.rgb = RGBColor(0, 0, 0)
    paragraph.paragraph_format.first_line_indent = Cm(1.25) if first_indent else None
    paragraph.paragraph_format.line_spacing = 1.5
    if align is not None:
        paragraph.alignment = align
    return paragraph


def insert_after(reference, element):
    """Вставляет абзац или таблицу сразу после указанного элемента документа."""
    reference_node = reference._p if hasattr(reference, "_p") else reference._tbl
    reference_node.addnext(element._p if hasattr(element, "_p") else element._tbl)


def insert_before(reference, element):
    """Вставляет абзац или таблицу перед указанным элементом документа."""
    reference_node = reference._p if hasattr(reference, "_p") else reference._tbl
    reference_node.addprevious(element._p if hasattr(element, "_p") else element._tbl)


def add_table_after(document, reference, caption: str, rows: list[list[str]]):
    """Добавляет ссылку, надтабличную подпись и аккуратно оформленную таблицу."""
    explainer = document.add_paragraph(
        f"Сводные данные и результаты проверки приведены в таблице «{caption}»."
    )
    explainer.paragraph_format.first_line_indent = Cm(1.25)
    explainer.paragraph_format.line_spacing = 1.5
    caption_paragraph = document.add_paragraph(f"Таблица — {caption}")
    caption_paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    caption_paragraph.paragraph_format.keep_with_next = True
    caption_paragraph.paragraph_format.first_line_indent = None
    caption_paragraph.paragraph_format.line_spacing = 1.0
    for run in caption_paragraph.runs:
        run.font.name = FONT
        run.font.size = Pt(14)
        run.font.color.rgb = RGBColor(0, 0, 0)

    table = document.add_table(rows=len(rows), cols=len(rows[0]))
    try:
        table.style = "Table Grid"
    except KeyError:
        borders = OxmlElement("w:tblBorders")
        for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
            border = OxmlElement(f"w:{edge}")
            border.set(qn("w:val"), "single")
            border.set(qn("w:sz"), "4")
            border.set(qn("w:color"), "808080")
            borders.append(border)
        table._tbl.tblPr.append(borders)
    for row_index, row in enumerate(rows):
        for col_index, value in enumerate(row):
            cell = table.cell(row_index, col_index)
            cell.text = str(value)
            for paragraph in cell.paragraphs:
                paragraph.paragraph_format.first_line_indent = None
                paragraph.paragraph_format.line_spacing = 1.0
                for run in paragraph.runs:
                    run.font.name = FONT
                    run.font.size = Pt(10)
                    run.font.color.rgb = RGBColor(0, 0, 0)
                    if row_index == 0:
                        run.bold = True

    insert_after(reference, explainer)
    insert_after(explainer, caption_paragraph)
    insert_after(caption_paragraph, table)
    return table


def add_figure_after(document, reference, image_path: Path, caption: str, explanation: str, figure_number: int = 1):
    """Размещает пояснение, изображение по центру и подпись рисунка."""
    explanation = explanation.replace("на рисунке", f"на рисунке {figure_number}")
    explanation_paragraph = document.add_paragraph(explanation)
    explanation_paragraph.paragraph_format.first_line_indent = Cm(1.25)
    explanation_paragraph.paragraph_format.line_spacing = 1.5
    image_paragraph = document.add_paragraph()
    image_paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    image_paragraph.paragraph_format.keep_with_next = True
    image_paragraph.add_run().add_picture(str(image_path), width=Cm(15))
    caption_paragraph = document.add_paragraph(f"Рисунок — {caption}")
    caption_paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    caption_paragraph.paragraph_format.first_line_indent = None
    caption_paragraph.paragraph_format.line_spacing = 1.0
    for run in caption_paragraph.runs:
        run.font.name = FONT
        run.font.size = Pt(14)
        run.font.color.rgb = RGBColor(0, 0, 0)
    insert_after(reference, explanation_paragraph)
    insert_after(explanation_paragraph, image_paragraph)
    insert_after(image_paragraph, caption_paragraph)
    return caption_paragraph


def sha256(path: Path) -> str:
    """Вычисляет контрольную сумму SHA-256 для выбранного файла."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


