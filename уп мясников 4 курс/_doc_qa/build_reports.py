def fill_final_report(source: Path):
    """Подставляет данные студента и наименования тем в итоговый отчёт."""
    document = Document(source)
    for paragraph in document.paragraphs:
        if "Студент(-ка) 4 курса" in paragraph.text:
            set_text(paragraph, "Студент 4 курса 4ИСИП-N23 учебной группы", first_indent=False)
        elif "И.О. Фамилия" in paragraph.text:
            set_text(paragraph, "Кулемин Артём Ильич", align=WD_ALIGN_PARAGRAPH.CENTER, first_indent=False)

    report_table = document.tables[0]
    for row in report_table.rows[1:]:
        for cell in row.cells:
            if "И.О. Фамилия" in cell.text:
                cell.text = "Кулемин Артём Ильич"
            elif "____" in cell.text or cell.text.strip() == "":
                continue
    target = OUTPUT / "Итоговый отчет УП — Кулемин Артём Ильич.docx"
    document.save(target)
    return target


